// Run: node scripts/cfb-calibration-report.cjs
// Baseline is the working engine captured before the CFB audit (including NFL).
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const {gunzipSync} = require('node:zlib');
const core = require('../rating-core.js');
const cfb = require('../test/helpers/cfb-calibration.cjs');
const nfl = require('../test/helpers/nfl-calibration.cjs');
const baseline = require('../calibration/cfb-baseline.json');
const root = path.resolve(__dirname,'..');
const frozenSource = gunzipSync(fs.readFileSync(path.join(root,'test/fixtures/scoring-core-before-cfb.js.gz'))).toString();
const before = vm.runInNewContext(`${frozenSource}\nSportsRadarScore`);
const labels = {
  A:'3-point game, Q2',B:'3-point game, 5:00 Q4',C:'Down 5, ball, 1:30',D:'Down 5, opponent ball, zero TO',E:'Same, three TO',
  F:'Tied at opponent 35, 1:00',G:'Down 14, ball, 8:00',H:'Down 21, ball, 8:00',I:'Down 21, ball, 2:00',
  J:'+7 dog leads by 3',K:'+21 dog leads by 3',L:'+28 dog tied',M:'+21 dog down 3, ball',N:'+21 dog down 17',
  O:'Unranked dog leads No. 2',P:'No. 1 vs No. 2 tied',Q:'Final fourth down',R:'Critical tying two-point try',
  S:'First OT opening possession',T:'OT response needs TD',U:'3OT response two-point try',V:'Championship decisive OT try',
  W:'No. 1 leads ranked opponent by 35',X:'10-7 with defensive action',Y:'10-7 with empty possessions'
};
function table(lines,headers,rows) {
  lines.push(`| ${headers.join(' | ')} |`,`| ${headers.map(()=> '---').join(' | ')} |`);
  for(const row of rows) lines.push(`| ${row.join(' | ')} |`);
  lines.push('');
}
async function main() {
  const results = Object.fromEntries(Object.entries(cfb.cases).map(([k,v])=>[k,cfb.evaluate(core,v)]));
  const lines = ['# CFB calibration report','','Generated by `node scripts/cfb-calibration-report.cjs`. Synthetic cases use full rate → snapshot → history aggregation. Baseline predates only this CFB audit, including the latest NFL decisive calibration.','',
    '## A–Y before/after',''];
  table(lines,['Case','State','Before','After','Base','Live bonus','Upset'],Object.entries(results).map(([k,v])=>[k,labels[k],baseline.cfb[k].score,v.score,v.base,v.bonus,v.upset]));
  const s = key => results[key].score;
  const assertions = [
    ['F > C > B > A',s('F')>s('C') && s('C')>s('B') && s('B')>s('A')],
    ['C > E > D',s('C')>s('E') && s('E')>s('D')],['G > H > I',s('G')>s('H') && s('H')>s('I')],
    ['K > J by at least 4',s('K')>=s('J')+4],['L >= K',s('L')>=s('K')],['M > N',s('M')>s('N')],
    ['O > equivalent unranked matchup K',s('O')>s('K')],['P >= 94 and P > F',s('P')>=94 && s('P')>s('F')],
    ['Q > ordinary 3:00 fourth down',s('Q')>cfb.evaluate(core,{...cfb.cases.Q,clock:'3:00'}).score],
    ['R > routine early try',s('R')>cfb.evaluate(core,{...cfb.cases.R,period:1,clock:'9:00'}).score],
    ['U >= T > S',s('U')>=s('T') && s('T')>s('S')],['V = 99 and V >= U',s('V')===99 && s('V')>=s('U')],
    ['W < 20 and W < P - 60',s('W')<20 && s('W')<s('P')-60],
    ['X = Y (live stagnation disabled)',s('X')===s('Y')]
  ];
  for(const [name,passed] of assertions) assert.ok(passed,name);
  lines.push('## Relative assertions','');
  table(lines,['Assertion','Result'],assertions.map(([name,passed])=>[name,passed?'PASS':'FAIL']));
  lines.push('## Margin × time grid','','Each cell is **before → after**. Trailing team owns the ball at its 25; no timeout information. Halftime is Q2 0:00. These are watchability scores, not comeback probabilities.','');
  table(lines,['Time remaining','Down 7','Down 10','Down 14','Down 17','Down 21','Down 28'],['30:00','15:00','8:00','4:00','2:00'].map(time=>[time,...[7,10,14,17,21,28].map(gap=>{
    const k=`${time}/${gap}`;return `${baseline.margins[k].score} → ${cfb.evaluate(core,cfb.margins[k]).score}`;
  })]));
  lines.push('## Spread scale','','Cells show final score / upset component. Late cases are 1:30 Q4; leading dogs face an opposing possession. Magnitude saturates at +30. Qualification is unchanged; +7 live activation intentionally changes from zero to one half.','');
  table(lines,['Spread','Leads by 3','Tied','Down 3 with ball','Down 17','Leads by 21 at half'],[7,10,14,21,28,30,40].map(spread=>[spread,...[
    {...cfb.cases.K,spread},{...cfb.cases.L,spread},{...cfb.cases.M,spread},{...cfb.cases.N,spread},
    {...cfb.cases.K,spread,scores:[21,42],period:2,clock:'0:00'}
  ].map(input=>{const r=cfb.evaluate(core,input);return `${r.score} / ${r.upset}`;})]));
  lines.push('## Rank interaction','');
  table(lines,['Favorite','Dog','Score','Upset'],[[null,null],[20,null],[5,null],[2,null],[2,20],[2,1]].map(ranks=>{
    const r=cfb.evaluate(core,{...cfb.cases.K,ranks});return [ranks[0]||'Unranked',ranks[1]||'Unranked',r.score,r.upset];
  }));
  lines.push('## NFL exact regression','');
  table(lines,['Case','Before','After','All components identical'],Object.entries(nfl.cases).map(([k,input])=>{
    const after=nfl.evaluate(core,input),old=nfl.evaluate(before,input);
    assert.deepEqual(old,baseline.nfl[k]);assert.deepEqual(after,old);
    return [k,old.score,after.score,'YES'];
  }));
  const display = await import('../alerts-worker/src/display-model.js');
  const currentAdapter = await import('../alerts-worker/src/game-model.js');
  const adapterSource = fs.readFileSync(path.join(root,'alerts-worker/src/game-model.js'),'utf8')
    .replace(/^import .*;\s*$/gm,'').replace(/^export .*;\s*$/gm,'');
  const cappedSource = require('../test/helpers/cap-pregame-oracle.cjs').capPregameOracle(frozenSource);
  const oldAdapter = vm.runInNewContext(`${cappedSource}\n${adapterSource}\n({normalizeEvent,enrichGame})`,{
    baseballSituation:display.baseballSituation,footballSituation:display.footballSituation
  });
  const dir=path.join(root,'test/fixtures/real-games');
  const real=[];
  const bySport={};
  for(const file of fs.readdirSync(dir).filter(name=>name.endsWith('.json')).sort()) {
    const input=JSON.parse(fs.readFileSync(path.join(dir,file),'utf8'));
    const evaluate = adapter => {
      const game=adapter.normalizeEvent(structuredClone(input.event),input.modelSport);
      if((game.state!=='upcoming' || !game.line) && !(game.division==='FCS' && game.state==='upcoming')) adapter.enrichGame(game,structuredClone(input.summary));
      return structuredClone(game);
    };
    const old=evaluate(oldAdapter),now=evaluate(currentAdapter);
    (bySport[input.modelSport] ||= {count:0,identical:0}).count++;
    const identical=JSON.stringify(old)===JSON.stringify(now);
    if(identical) bySport[input.modelSport].identical++;
    // NHL was independently calibrated after this historical CFB baseline.
    // Its exact immediate-baseline regression lives in midgame-calibration.
    if(!['CFB','NHL'].includes(input.modelSport) || now.state==='upcoming') assert.deepEqual(now,old,`${file}: preserved complete adapter output`);
    if(input.modelSport==='CFB') assert.deepEqual(structuredClone(core.momentumImpact('CFB',input.summary,1,now.state)),
      structuredClone(before.momentumImpact('CFB',input.summary,1,now.state)),`${file}: shared history preserved`);
    if(input.modelSport==='CFB') {
      const period=Number(input.event.competitions[0].status.period);
      const candidate=now.underdog || core.underdogCandidate('CFB',input.event.competitions[0],input.event.competitions[0].odds?.[0]);
      const history=core.momentumImpact('CFB',input.summary,1,'completed');
      real.push({file,matchup:now.teams.map(t=>t[0]).join(' vs '),scoreline:now.teams.map(t=>t[2]).join('-'),
        period,before:old.score,after:now.score,base:now.baseScore,history:now.momentumPoints||0,
        spread:candidate?.value ?? null,upset:now.upsetPoints||0,
        ranks:now.teams.map(t=>t[6]),factors:now.factors,
        tags:[...(period>4?[`${period-4}OT`]:[]),...(now.teams.every(t=>t[6])?['ranked pairing']:[]),
          ...(now.upsetPoints?[candidate?.value>=21?'giant upset':'upset']:[]),...(history.factors.some(f=>/erased a large deficit/i.test(f.label))?['comeback']:[]),
          ...(Math.abs(Number(now.teams[0][2])-Number(now.teams[1][2]))>=28?['blowout']:[]),
          ...(now.teams.reduce((sum,t)=>sum+Number(t[2]),0)<=35?['low scoring']:[]),
          ...(now.teams.reduce((sum,t)=>sum+Number(t[2]),0)>=75?['shootout']:[])]});
    }
  }
  lines.push('## Stored provider fixtures','','Full normalization/enrichment, including completed histories and final bonuses, ran through both the frozen pre-change engine and current engine. Completed CFB was subsequently calibrated separately; see [the completed calibration report](cfb-completed-calibration.md) for its immediate before/after baseline. Standalone histories remain identical.','');
  table(lines,['Sport','Fixtures','Complete outputs identical'],Object.entries(bySport).map(([sport,v])=>[sport,v.count,v.identical]));
  lines.push('### All stored CFB results','');
  table(lines,['Matchup (same order as final)','Final','Before','After','Base','History','Coverage'],real.map(r=>[r.matchup,r.scoreline,r.before,r.after,r.base,r.history,r.tags.join(', ')]));
  lines.push('All 50 stored CFB fixtures are completed games; none is a captured live scoreboard snapshot. There is one 2OT result and two 1OT results, but no 3OT+ result. This validates completed behavior and adapter compatibility; synthetic tests provide the possession/timeout and shootout coverage.','',
    'These fixtures are stored provider captures, not fresh external verification. Low final totals alone cannot establish defensive quality; use the underlying history and defensive-action tests. No runtime game IDs or outcomes were added.','',
    'See [cfb-scoring-audit.md](cfb-scoring-audit.md) for formulas, provider assumptions, limitations, and test commands.','');
  fs.writeFileSync(path.join(root,'calibration/cfb-calibration.md'),lines.join('\n'));
  console.log(JSON.stringify({syntheticCases:Object.keys(results).length,relativeAssertions:assertions.length,nflCases:16,providerFixtures:bySport,cfbReal:real.length},null,2));
}
main().catch(error=>{console.error(error);process.exitCode=1;});
